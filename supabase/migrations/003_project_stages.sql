-- Этапы хранятся как JSONB-массив объектов:
--   [{ "id": "...", "title": "Составление ТЗ", "description": "...", "done": false }, ...]
-- Прогресс проекта (projects.progress) пересчитывается из доли выполненных этапов.
alter table projects
  add column if not exists stages jsonb not null default '[]'::jsonb;
